export const ICON_NAMES = Object.keys(LIGATURES)

function Icon({ name, size, className = '', style, ...rest }) {
  const glyph = LIGATURES[name]
  if (!glyph) return null
  const s = size ? { width: size, height: size, fontSize: size } : null
  return (
    <span
      className={'icn ' + className}
      data-icon={name}
      data-glyph={glyph}
      aria-hidden="true"
      style={{ fontVariationSettings: `'FILL' 1,'wght' 400,'GRAD' 0,'opsz' 24`, ...s, ...style }}
      {...rest}
    />
  )
}

export default memo(Icon)
